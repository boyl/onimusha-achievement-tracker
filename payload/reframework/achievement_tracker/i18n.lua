function L.select(game_language)
    return (game_language=="SimplelifiedChinese" or game_language=="TransitionalChinese") and "zh" or "en"
end
function L.translator(language)
    return function(key)
        if language=="zh" then return key end
        local value=assert(english[key],"Missing English translation: "..key)
        return value
    end
end
return L
